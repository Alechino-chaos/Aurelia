/** Labels may change while existing provider request values remain independent. */
export function targetLabel(value: string, locale: UiLocale): string {
  if (value === '简体中文' || value === '繁體中文' || value === '日本語') return uiText(value, {}, locale);
  if (value === 'Deutsch') return uiText('germanTarget', {}, locale);
  if (value === 'Français') return uiText('frenchTarget', {}, locale);
  return value;
}

/** Cached renderer notices retain their parameters until display in the current language. */
export function uiMessage<K extends keyof typeof rendererZh>(key: K, parameters: MessageParameters<(typeof rendererZh)[K]>): string {
  return '[[aurelia-renderer]]' + JSON.stringify({ key, parameters });
}
export function displayMessage(value: string, locale: UiLocale): string {
  if (value.startsWith('[[aurelia-renderer-list]]')) {
    try { return JSON.parse(value.slice('[[aurelia-renderer-list]]'.length)).map((item: string) => displayMessage(item, locale)).join('\n'); } catch { return value; }
  }
  if (value.startsWith('[[aurelia-renderer]]')) {
    try { const { key, parameters } = JSON.parse(value.slice('[[aurelia-renderer]]'.length));
      if (Object.prototype.hasOwnProperty.call(rendererZh, key)) {
        const localized = Object.fromEntries(Object.entries(parameters).map(([name, detail]) => [name, name === 'detail' && typeof detail === 'string' ? translateBackendMessage(detail, locale) : detail]));
        return (uiText as any)(key, localized, locale);
      }
    } catch { /* Unknown messages stay intact. */ }
  }
  const backend = translateBackendMessage(value, locale);
  if (backend !== value || value.includes('[[aurelia-ui]]')) return backend;
  for (const key of Object.keys(rendererZh) as (keyof typeof rendererZh)[]) if (value === rendererZh[key] || value === rendererEn[key]) return (uiText as any)(key, {}, locale);
  return translateAppMessage(value, locale);
}
